function Update-VPASDependentAccount{
    [OutputType([bool],'System.Object')]
    [CmdletBinding(DefaultParameterSetName='Set1')]
    Param(

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true)]
        [String]$safe,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true)]
        [String]$platform,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true)]
        [String]$username,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true)]
        [String]$address,

        [Parameter(Mandatory=$true,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true,HelpMessage="Unique AccountID that references the target account (for example: 3_12)")]
        [Parameter(Mandatory=$true,ParameterSetName='Set4',ValueFromPipelineByPropertyName=$true,HelpMessage="Unique AccountID that references the target account (for example: 3_12)")]
        [String]$AcctID,

        [Parameter(Mandatory=$true,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true,HelpMessage="Search string to find target dependent account (for example: WinService01)")]
        [Parameter(Mandatory=$true,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true,HelpMessage="Search string to find target dependent account (for example: WinService01)")]
        [String]$DependentSearchQuery,

        [Parameter(Mandatory=$true,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true,HelpMessage="Unique DependentAccountID that references the target dependent account (for example: 3_13)")]
        [Parameter(Mandatory=$true,ParameterSetName='Set4',ValueFromPipelineByPropertyName=$true,HelpMessage="Unique DependentAccountID that references the target dependent account (for example: 3_13)")]
        [String]$DependentAcctID,

        [Parameter(Mandatory=$true,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter target field to update (Name, AutomaticManagementEnabled, ManualManagementReason, PlatformProperty)")]
        [Parameter(Mandatory=$true,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter target field to update (Name, AutomaticManagementEnabled, ManualManagementReason, PlatformProperty)")]
        [Parameter(Mandatory=$true,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter target field to update (Name, AutomaticManagementEnabled, ManualManagementReason, PlatformProperty)")]
        [Parameter(Mandatory=$true,ParameterSetName='Set4',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter target field to update (Name, AutomaticManagementEnabled, ManualManagementReason, PlatformProperty)")]
        [ValidateSet('Name','AutomaticManagementEnabled','ManualManagementReason','PlatformProperty')]
        [String]$field,

        [Parameter(Mandatory=$true,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter updated value for target field")]
        [Parameter(Mandatory=$true,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter updated value for target field")]
        [Parameter(Mandatory=$true,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter updated value for target field")]
        [Parameter(Mandatory=$true,ParameterSetName='Set4',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter updated value for target field")]
        [String]$fieldval,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set3',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set4',ValueFromPipelineByPropertyName=$true)]
        [String]$PlatformProperty,

        [Parameter(Mandatory=$true,ParameterSetName='InputParameters',ValueFromPipelineByPropertyName=$true,HelpMessage="Hashtable of parameters required to make API call, refer to get-help -examples for valid inputs")]
        [hashtable]$InputParameters,

        [Parameter(Mandatory=$false,ValueFromPipelineByPropertyName=$true)]
        [hashtable]$token
    )

    Begin{
        $tokenval,$sessionval,$PVWA,$Header,$ISPSS,$IdentityURL,$EnableTextRecorder,$AuditTimeStamp,$NoSSL,$VaultVersion,$HideWarnings,$AuthenticatedAs,$SubDomain,$EnableTroubleshooting,$APICounter,$Creds,$AuthType,$IDPLogin,$SRS = Get-VPASSession -token $token
        $CommandName = $MyInvocation.MyCommand.Name
        $log = Write-VPASTextRecorder -inputval $CommandName -token $token -LogType COMMAND
    }
    Process{
        try{
            if($PSCmdlet.ParameterSetName -eq "InputParameters"){
                $KeyHash = @{
                    set1 = @{
                        AcceptableKeys = @("safe","platform","username","address","DependentSearchQuery","field","fieldval","PlatformProperty")
                        MandatoryKeys = @("DependentSearchQuery","field","fieldval")
                    }
                    set2 = @{
                        AcceptableKeys = @("AcctID","DependentSearchQuery","field","fieldval","PlatformProperty")
                        MandatoryKeys = @("AcctID","DependentSearchQuery","field","fieldval")
                    }
                    set3 = @{
                        AcceptableKeys = @("safe","platform","username","address","DependentAcctID","field","fieldval","PlatformProperty")
                        MandatoryKeys = @("DependentAcctID","field","fieldval")
                    }
                    set4 = @{
                        AcceptableKeys = @("AcctID","DependentAcctID","field","fieldval","PlatformProperty")
                        MandatoryKeys = @("AcctID","DependentAcctID","field","fieldval")
                    }
                }
                $CheckSet = Test-VPASHashtableKeysHelper -InputHash $InputParameters -KeyHash $KeyHash

                if(!$CheckSet){
                    $log = Write-VPASTextRecorder -inputval "FAILED TO FIND TARGET PARAMETER SET" -token $token -LogType MISC
                    Write-Verbose "FAILED TO FIND TARGET PARAMETER SET"
                    Write-VPASOutput -str "FAILED TO FIND TARGET PARAMETER SET...VIEW EXAMPLES BELOW:" -type E
                    $examples = Write-VPASExampleHelper -CommandName $CommandName
                    return $false
                }
                else{
                    foreach($key in $InputParameters.Keys){
                        Set-Variable -Name $key -Value $InputParameters.$key
                    }
                }
            }
        }catch{
            $log = Write-VPASTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-Verbose "FAILED TO RESUME DEPENDENT ACCOUNT"
            Write-VPASOutput -str $_ -type E
            return $false
        }

        try{
            if([String]::IsNullOrEmpty($AcctID)){
                Write-Verbose "NO ACCTID PROVIDED...INVOKING HELPER FUNCTION TO RETRIEVE UNIQUE ACCOUNT ID BASED ON SPECIFIED PARAMETERS"
                $AcctID = Get-VPASAccountIDHelper -token $token -safe $safe -platform $platform -username $username -address $address

                if($AcctID -eq -1){
                    $log = Write-VPASTextRecorder -inputval "COULD NOT FIND UNIQUE ACCOUNT ENTRY, INCLUDE MORE SEARCH PARAMETERS" -token $token -LogType MISC
                    $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                    Write-Verbose "COULD NOT FIND UNIQUE ACCOUNT ENTRY, INCLUDE MORE SEARCH PARAMETERS"
                    Write-VPASOutput -str "COULD NOT FIND UNIQUE ACCOUNT ENTRY, INCLUDE MORE SEARCH PARAMETERS" -type E
                    return $false
                }
                elseif($AcctID -eq -2){
                    $log = Write-VPASTextRecorder -inputval "NO ACCOUNTS FOUND" -token $token -LogType MISC
                    $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                    Write-Verbose "NO ACCOUNTS FOUND"
                    Write-VPASOutput -str "NO ACCOUNTS FOUND" -type E
                    return $false
                }
                else{
                    Write-Verbose "RETURNING ACCOUNT ID: $AcctID"
                }
            }
            else{
                Write-Verbose "ACCTID SUPPLIED, SKIPPING HELPER FUNCTION"
            }

            if([String]::IsNullOrEmpty($DependentAcctID)){
                Write-Verbose "NO DEPENDENT ACCTID PROVIDED...INVOKING HELPER FUNCTION TO RETRIEVE UNIQUE DEPENDENT ACCOUNT ID BASED ON SPECIFIED PARAMETERS"
                $DependentAcctID = Get-VPASDependentAccountIDHelper -token $token -AcctID $AcctID -searchquery $DependentSearchQuery

                if($DependentAcctID -eq -1){
                    $log = Write-VPASTextRecorder -inputval "COULD NOT FIND UNIQUE DEPENDENT ACCOUNT ENTRY, INCLUDE MORE SEARCH PARAMETERS" -token $token -LogType MISC
                    $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                    Write-Verbose "COULD NOT FIND UNIQUE DEPENDENT ACCOUNT ENTRY, INCLUDE MORE SEARCH PARAMETERS"
                    Write-VPASOutput -str "COULD NOT FIND UNIQUE DEPENDENT ACCOUNT ENTRY, INCLUDE MORE SEARCH PARAMETERS" -type E
                    return $false
                }
                elseif($DependentAcctID -eq -2){
                    $log = Write-VPASTextRecorder -inputval "NO DEPENDENT ACCOUNTS FOUND" -token $token -LogType MISC
                    $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                    Write-Verbose "NO DEPENDENT ACCOUNTS FOUND"
                    Write-VPASOutput -str "NO DEPENDENT ACCOUNTS FOUND" -type E
                    return $false
                }
                else{
                    Write-Verbose "RETURNING DEPENDENT ACCOUNT ID: $DependentAcctID"
                }
            }
            else{
                Write-Verbose "DEPENDENT ACCTID SUPPLIED, SKIPPING HELPER FUNCTION"
            }

            Write-Verbose "RETRIEVING CURRENT DEPENDENT ACCOUNT PARAMETERS"
            $CurrentValues = Get-VPASDependentAccountDetails -AcctID $AcctID -DependentAcctID $DependentAcctID -token $token


            write-verbose "INITIALIZING API PARAMETERS"
            if($ISPSS){
                $params = @{
                    name = $CurrentValues.name
                    platformDependentProperties = $CurrentValues.platformDependentProperties
                    secretManagement = $CurrentValues.secretManagement
                    platformId = $CurrentValues.platformId
                }
            }
            else{
                $params = @{
                    name = $CurrentValues.name
                    platformAccountProperties = $CurrentValues.platformAccountProperties
                    secretManagement = $CurrentValues.secretManagement
                    platformId = $CurrentValues.platformId
                }
            }

            $testval = $params.secretManagement.automaticManagementEnabled
            if([String]::IsNullOrEmpty($testval) -or $testval -eq $true){
                $params.secretManagement = @{}
            }

            Write-Verbose "UPDATING API PARAMETERS WITH UPDATED VALUE"
            if($field -eq "Name"){
                $params.name = $fieldval
                Write-Verbose "UPDATING API PARAMETERS WITH UPDATED NAME VALUE $fieldval"
            }
            elseif($field -eq "AutomaticManagementEnabled"){
                $params.secretManagement.automaticManagementEnabled = $fieldval
                Write-Verbose "UPDATING API PARAMETERS WITH UPDATED AUTOMATIC MANAGEMENT ENABLED VALUE: $fieldval"
            }
            elseif($field -eq "ManualManagementReason"){
                if($params.secretManagement.ManualManagementReason){
                    $params.secretManagement.ManualManagementReason = $fieldval
                    Write-Verbose "UPDATING API PARAMETERS WITH UPDATED MANUAL MANAGEMENT REASON VALUE $fieldval"
                }
                else{
                    $params.secretManagement | Add-Member -MemberType NoteProperty -Name "ManualManagementReason" -Value $fieldval
                    Write-Verbose "UPDATING API PARAMETERS WITH UPDATED MANUAL MANAGEMENT REASON VALUE $fieldval"
                }
            }
            elseif($field -eq "PlatformProperty"){
                if($ISPSS){
                    if([String]::IsNullOrEmpty($PlatformProperty)){
                        $log = Write-VPASTextRecorder -inputval "-field PlatformProperty WAS PASSED BUT NO PARAMETER -PlatformProperty WAS PASSED" -token $token -LogType MISC
                        $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                        Write-Verbose "-field PlatformProperty WAS PASSED BUT NO PARAMETER -PlatformProperty WAS PASSED"
                        Write-VPASOutput -str "-field PlatformProperty WAS PASSED BUT NO PARAMETER -PlatformProperty WAS PASSED" -type E
                        return $false
                    }
                    else{
                        if($params.platformDependentProperties.$PlatformProperty){
                            $params.platformDependentProperties.$PlatformProperty = $fieldval
                            Write-Verbose "UPDATING API PARAMETERS WITH UPDATED PLATFORM ACCOUNT PROPERTY $PlatformProperty VALUE $fieldval"
                        }
                        else{
                            $params.platformDependentProperties | Add-Member -MemberType NoteProperty -Name $PlatformProperty -Value $fieldval
                            Write-Verbose "UPDATING API PARAMETERS WITH UPDATED PLATFORM ACCOUNT PROPERTY $PlatformProperty VALUE $fieldval"
                        }
                    }
                }
                else{
                    if([String]::IsNullOrEmpty($PlatformProperty)){
                        $log = Write-VPASTextRecorder -inputval "-field PlatformProperty WAS PASSED BUT NO PARAMETER -PlatformProperty WAS PASSED" -token $token -LogType MISC
                        $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                        Write-Verbose "-field PlatformProperty WAS PASSED BUT NO PARAMETER -PlatformProperty WAS PASSED"
                        Write-VPASOutput -str "-field PlatformProperty WAS PASSED BUT NO PARAMETER -PlatformProperty WAS PASSED" -type E
                        return $false
                    }
                    else{
                        if($params.platformAccountProperties.$PlatformProperty){
                            $params.platformAccountProperties.$PlatformProperty = $fieldval
                            Write-Verbose "UPDATING API PARAMETERS WITH UPDATED PLATFORM ACCOUNT PROPERTY $PlatformProperty VALUE $fieldval"
                        }
                        else{
                            $params.platformAccountProperties | Add-Member -MemberType NoteProperty -Name $PlatformProperty -Value $fieldval
                            Write-Verbose "UPDATING API PARAMETERS WITH UPDATED PLATFORM ACCOUNT PROPERTY $PlatformProperty VALUE $fieldval"
                        }
                    }
                }
            }
            $log = Write-VPASTextRecorder -inputval $params -token $token -LogType PARAMS
            $params = $params | ConvertTo-Json
            Write-Verbose $params
            if($NoSSL){
                Write-Verbose "NO SSL ENABLED, USING HTTP INSTEAD OF HTTPS"
                if($ISPSS){
                    $uri = "http://$PVWA/API/accounts/$AcctID/account-dependents/$DependentAcctID"
                }
                else{
                    $uri = "http://$PVWA/PasswordVault/API/Accounts/$AcctID/dependentAccounts/$DependentAcctID"
                }
            }
            else{
                Write-Verbose "SSL ENABLED BY DEFAULT, USING HTTPS"
                if($ISPSS){
                    $uri = "https://$PVWA/API/accounts/$AcctID/account-dependents/$DependentAcctID"
                }
                else{
                    $uri = "https://$PVWA/PasswordVault/API/Accounts/$AcctID/dependentAccounts/$DependentAcctID"
                }
            }
            $log = Write-VPASTextRecorder -inputval $uri -token $token -LogType URI
            $log = Write-VPASTextRecorder -inputval "PUT" -token $token -LogType METHOD

            if($sessionval){
                $response = Invoke-RestMethod -Headers @{"Authorization"=$Header} -Uri $uri -Body $params -Method PUT -ContentType "application/json" -WebSession $sessionval
                $APICounter += 1
            }
            else{
                $response = Invoke-RestMethod -Headers @{"Authorization"=$Header} -Uri $uri -Body $params -Method PUT -ContentType "application/json"
                $APICounter += 1
            }
            $outputlog = $response
            $log = Write-VPASTextRecorder -inputval $outputlog -token $token -LogType RETURN
            Write-Verbose "RETURNING JSON OBJECT"
            return $response
        }catch{
            $log = Write-VPASTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-VPASOutput -str $_ -type E
            Write-Verbose "UNABLE TO UPDATE DEPENDENT ACCOUNT"
            return $false
        }
    }
    End{
        $log = Write-VPASTextRecorder -inputval $CommandName -token $token -LogType DIVIDER
        $token = Update-VPASSession -AddCounter $APICounter -InputToken $token
    }
}

