<#
.Synopsis
   Run various account metrics
   CREATED BY: Vadim Melamed, EMAIL: vpasmodule@gmail.com
.DESCRIPTION
   Use this function to generate various Account related metrics and KPIs
.LINK
   https://vpasmodule.com/commands.html#Invoke-VPASMetricsAccounts
.NOTES
   Category: PAM
   Tag: Metrics
   Since: v14.1.0
   Version: 9
   SelfHosted: TRUE
   PrivCloudStandard: TRUE
   SharedServices: TRUE
   SRS: TRUE
.PARAMETER token
   HashTable of data containing various pieces of login information (PVWA, LoginToken, HeaderType, etc).
   If -token is not passed, function will use last known hashtable generated by New-VPASToken
.PARAMETER TargetMetric
   Specify which report will be run
   Possible values: OnboardedAccountTypes, AccountsOnboardedXDays, AccountComplianceStatus
.PARAMETER MetricFormat
   Specify the report output format
   NONE will return the generated hashtable of data that can be assigned to a variable
   Possible values: JSON, HTML, ALL, NONE
.PARAMETER OutputDirectory
   Specify where the location for report output to be saved
.PARAMETER DayRange
   Specify the date range for the selected metric report
.PARAMETER AmtOfSets
   Specify the length of historic data to be included in the metric report
.PARAMETER HideRawData
   Removes the RawData visual from the exported output
   Helpful when exporting to a PDF or document to remove extra not needed information
.PARAMETER IgnoreSafes
   Wildcard value that will cause a record to be ignored from the metrics if the target record SafeName matches
.PARAMETER IgnorePlatforms
   Wildcard value that will cause a record to be ignored from the metrics if the target record PlatformID matches
.PARAMETER IgnoreUsernames
   Wildcard value that will cause a record to be ignored from the metrics if the target record Username matches
.PARAMETER SafeSearchQuery
   Wildcard value that will limit the metrics to only target records that match the searchquery via safe name
.PARAMETER PlatformSearchQuery
   Wildcard value that will limit the metrics to only target records that match the searchquery via platformID
.PARAMETER UsernameSearchQuery
   Wildcard value that will limit the metrics to only target records that match the searchquery via account username
.PARAMETER InputParameters
   HashTable of values containing the parameters required to make the API call
.EXAMPLE
   $GenerateReport = Invoke-VPASMetricsAccounts -TargetMetric {TARGET METRIC VALUE} -MetricFormat {METRIC FORMAT VALUE} -OutputDirectory {OUTPUT DIRECTORY VALUE}
.EXAMPLE
   $InputParameters = @{
        TargetMetric = "OnboardedAccountTypes"|"AccountsOnboardedXDays"|"AccountComplianceStatus"
		MetricFormat = "JSON"|"HTML"|"ALL"|"NONE"
		OutputDirectory = "C:\temp\ReportOutputs"
        DayRange = "7"
        AmtOfSets = "4"
        HideRawData = $true|$false
        IgnoreSafes = @("VaultInternal","System")
        IgnorePlatforms = @("WinDomain","WinLocal")
        IgnoreUsernames = @("IgnoreUsername1")
        SafeSearchQuery = @("vman-","vpas-")
        PlatformSearchQuery = @("norotate","store")
        UsernameSearchQuery = @("TargetUser1","TargetUser3")
   }
   $GenerateReport = Invoke-VPASMetricsAccounts -InputParameters $InputParameters
.OUTPUTS
   If successful:
   HashTable object of metric data
        Output varies upon selected metric
   ---
   $false if failed
#>
function Invoke-VPASMetricsAccounts{
    [OutputType([bool])]
    [CmdletBinding(DefaultParameterSetName='Set1')]
    Param(

        [Parameter(Mandatory=$true,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter TargetMetric to be generated (OnboardedAccountTypes, AccountsOnboardedXDays, AccountComplianceStatus)")]
        [ValidateSet('OnboardedAccountTypes','AccountsOnboardedXDays','AccountComplianceStatus')]
        [String]$TargetMetric,

        [Parameter(Mandatory=$true,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true,HelpMessage="Enter ReportOutput type (JSON, HTML, ALL, NONE)")]
        [ValidateSet('JSON','HTML','ALL','NONE')]
        [String]$MetricFormat,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$OutputDirectory,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$DayRange,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$AmtOfSets,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [switch]$HideRawData,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String[]]$IgnoreSafes,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String[]]$IgnorePlatforms,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String[]]$IgnoreUsernames,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String[]]$SafeSearchQuery,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String[]]$PlatformSearchQuery,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String[]]$UsernameSearchQuery,

        [Parameter(Mandatory=$true,ParameterSetName='InputParameters',ValueFromPipelineByPropertyName=$true,HelpMessage="Hashtable of parameters required to make API call, refer to get-help -examples for valid inputs")]
        [hashtable]$InputParameters,

        [Parameter(Mandatory=$false,ValueFromPipelineByPropertyName=$true)]
        [hashtable]$token
    )

    Begin{
        $tokenval,$sessionval,$PVWA,$Header,$ISPSS,$IdentityURL,$EnableTextRecorder,$AuditTimeStamp,$NoSSL,$VaultVersion,$HideWarnings,$AuthenticatedAs,$SubDomain,$EnableTroubleshooting,$APICounter,$Creds,$AuthType,$IDPLogin,$SRS = Get-VPASSession -token $token
        $CommandName = $MyInvocation.MyCommand.Name
        $log = Write-VPASTextRecorder -inputval $CommandName -token $token -LogType COMMAND
    }
    Process{

        try{
            if($PSCmdlet.ParameterSetName -eq "InputParameters"){
                $KeyHash = @{
                    set1 = @{
                        AcceptableKeys = @("TargetMetric","MetricFormat","OutputDirectory","DayRange","AmtOfSets","HideRawData","IgnoreSafes","IgnorePlatforms","IgnoreUsernames","SafeSearchQuery","PlatformSearchQuery","UsernameSearchQuery")
                        MandatoryKeys = @("TargetMetric","MetricFormat")
                    }
                }
                $CheckSet = Test-VPASHashtableKeysHelper -InputHash $InputParameters -KeyHash $KeyHash

                if(!$CheckSet){
                    $log = Write-VPASTextRecorder -inputval "FAILED TO FIND TARGET PARAMETER SET" -token $token -LogType MISC
                    Write-Verbose "FAILED TO FIND TARGET PARAMETER SET"
                    Write-VPASOutput -str "FAILED TO FIND TARGET PARAMETER SET...VIEW EXAMPLES BELOW:" -type E
                    $examples = Write-VPASExampleHelper -CommandName $CommandName
                    return $false
                }
                else{
                    foreach($key in $InputParameters.Keys){
                        Set-Variable -Name $key -Value $InputParameters.$key
                    }
                }
            }
        }catch{
            $log = Write-VPASTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-Verbose "FAILED TO INVOKE METRIC"
            Write-VPASOutput -str $_ -type E
            return $false
        }

        try{
            $SkipPlatformsSTR = ""
            foreach($rec in $IgnorePlatforms){
                $SkipPlatformsSTR += "*" + $rec + "*; "
            }
            $SkipUsernameSTR = ""
            foreach($rec in $IgnoreUsernames){
                $SkipUsernameSTR += "*" + $rec + "*; "
            }
            $SkipSafeSTR = ""
            foreach($rec in $IgnoreSafes){
                $SkipSafeSTR += "*" + $rec + "*; "
            }
            $TargetSafeSTR = ""
            foreach($rec in $SafeSearchQuery){
                $TargetSafeSTR += "*" + $rec + "*; "
            }
            $TargetPlatformSTR = ""
            foreach($rec in $PlatformSearchQuery){
                $TargetPlatformSTR += "*" + $rec + "*; "
            }
            $TargetUsernameSTR = ""
            foreach($rec in $UsernameSearchQuery){
                $TargetUsernameSTR += "*" + $rec + "*; "
            }

            if($MetricFormat -ne "NONE"){
                if([String]::IsNullOrEmpty($OutputDirectory)){
                    $curUser = $env:UserName
                    $OutputDirectory = "C:\Users\$curUser\AppData\Local\VPASModuleOutputs\Metrics"
                    Write-Verbose "NO OUTPUT DIRECTORY SUPPLIED, USING DEFAULT LOCATION: $OutputDirectory"

                    if(Test-Path -Path $OutputDirectory){
                        #DO NOTHING
                    }
                    else{
                        write-verbose "$OutputDirectory DOES NOT EXIST, CREATING DIRECTORY"
                        $MakeDirectory = New-Item -Path $OutputDirectory -Type Directory
                    }
                }
                else{
                    if(Test-Path -Path $OutputDirectory){
                        #DO NOTHING
                    }
                    else{
                        $curUser = $env:UserName
                        write-verbose "$OutputDirectory DOES NOT EXIST, USING DEFAULT LOCATION: C:\Users\$curUser\AppData\Local\VPASModuleOutputs\Metrics"
                        $OutputDirectory = "C:\Users\$curUser\AppData\Local\VPASModuleOutputs\Metrics"
                        if(Test-Path -Path $OutputDirectory){
                            #DO NOTHING
                        }
                        else{
                            $MakeDirectory = New-Item -Path $OutputDirectory -Type Directory
                        }
                    }
                }
            }

            if([String]::IsNullOrEmpty($HTMLChart)){
                $HTMLChart = "PieChart"
            }

            if($TargetMetric -eq "OnboardedAccountTypes"){
                $tagout = "accounts"
                #INITIALIZE HASH
                $OutputHash = @{}
                $PlatformLookup = @{}

                $TempPlatforms = Get-VPASAllPlatforms -token $token
                if(!$TempPlatforms){
                    Write-Verbose "FAILED TO RETRIEVE PLATFORMS"
                    Write-VPASOutput -str "FAILED TO RETRIEVE PLATFORMS" -type E
                    Write-VPASOutput -str $_ -type E
                    return $false
                }
                if($PlatformSearchQuery.count -gt 0){
                    $PlatformMatrix = @()
                    $AllPlatforms = @{
                        Platforms = @()
                        Total = 0
                    }
                    foreach($plat in $TempPlatforms.Platforms){
                        $targetplatID = $plat.general.id
                        foreach($query in $PlatformSearchQuery){
                            if($targetplatID -match $query){
                                if(!$PlatformMatrix.Contains($targetplatID)){
                                    $AllPlatforms.Platforms += $plat
                                    $AllPlatforms.Total += 1
                                    $PlatformMatrix += $targetplatID
                                }
                            }
                        }
                    }

                }
                else{
                    $AllPlatforms = $TempPlatforms
                }

                foreach($plat in $AllPlatforms.Platforms){
                    $PlatType = $plat.general.systemType
                    $PlatID = $plat.general.id

                    $PlatformLookup += @{
                        $PlatID = $PlatType
                    }

                    if(!$OutputHash.$PlatType){
                        $OutputHash += @{
                            #$PlatType = 0
                            $PlatType = @{
                                counter = 0
                                RawData = @()
                            }
                        }
                    }
                }
                $PlatformLookup += @{
                    "BLANK_PLATFORM" = "Unknown"
                }
                $OutputHash += @{
                    "Unknown" = @{
                        counter = 0
                        RawData = @()
                    }
                }

                $AllAccounts = Get-VPASAllAccounts -token $token
                if(!$AllAccounts){
                    Write-Verbose "FAILED TO PULL ALL ACCOUNTS"
                    Write-VPASOutput -str "FAILED TO PULL ALL ACCOUNTS" -type E
                    Write-VPASOutput -str $_ -type E
                    return $false
                }
                foreach($rec in $AllAccounts.value){
                    $validtargetplatform = $false
                    $validtargetsafe = $false
                    $validtargetusername = $false
                    $targetPlat = $rec.platformID
                    $targetSafe = $rec.safeName
                    $targetUsername = $rec.userName
                    $targetAccountName = $rec.name
                    $skipval = $false

                    if($PlatformSearchQuery.Count -eq 0){
                        $validtargetplatform = $true
                    }
                    else{
                        foreach($query in $PlatformSearchQuery){
                            if($targetPlat -match $query){
                                $validtargetplatform = $true
                            }
                        }
                    }

                    if($UsernameSearchQuery.Count -eq 0){
                        $validtargetusername = $true
                    }
                    else{
                        foreach($query in $UsernameSearchQuery){
                            if($targetUsername -match $query){
                                $validtargetusername = $true
                            }
                        }
                    }

                    if($SafeSearchQuery.Count -eq 0){
                        $validtargetsafe = $true
                    }
                    else{
                        foreach($query in $SafeSearchQuery){
                            if($targetSafe -match $query){
                                $validtargetsafe = $true
                            }
                        }
                    }

                    if(!$validtargetplatform -or !$validtargetsafe -or !$validtargetusername){
                        $skipval = $true
                    }

                    if(!$skipval){
                        foreach($ignoreval in $IgnoreSafes){
                            if($targetSafe -match $ignoreval){
                                Write-Verbose "SKIPPING $targetAccountName : SKIP VALUE $ignoreval FOUND IN SAFE $targetSafe"
                                $skipval = $true
                            }
                        }
                    }

                    if(!$skipval){
                        foreach($ignoreval in $IgnorePlatforms){
                            if($targetPlat -match $ignoreval){
                                Write-Verbose "SKIPPING $targetAccountName : SKIP VALUE $ignoreval FOUND IN PLATFORM $targetPlat"
                                $skipval = $true
                            }
                        }
                    }

                    if(!$skipval){
                        foreach($ignoreval in $IgnoreUsernames){
                            if($targetUsername -match $ignoreval){
                                Write-Verbose "SKIPPING $targetAccountName : SKIP VALUE $ignoreval FOUND IN USERNAME $targetUsername"
                                $skipval = $true
                            }
                        }
                    }

                    if(!$skipval){
                        if([String]::IsNullOrEmpty($targetPlat)){
                            $targetPlat = "BLANK_PLATFORM"
                        }
                        if($PlatformLookup.$targetPlat){
                            $lookupKey = $PlatformLookup.$targetPlat
                            $OutputHash.$lookupKey.counter += 1
                            $OutputHash.$lookupKey.RawData += $rec
                        }
                    }
                }

                if($MetricFormat -eq "JSON" -or $MetricFormat -eq "ALL"){
                    $outputfile = "$OutputDirectory/OnboardedAccountTypes.json"
                    $OutputDataJSON = $OutputHash | ConvertTo-Json -Depth 100
                    Write-Output $OutputDataJSON | Set-Content $outputfile
                }
                if($MetricFormat -eq "NONE"){
                    $htmlData += @{
                        datahash = $OutputHash
                    }
                }
                if($MetricFormat -eq "HTML" -or $MetricFormat -eq "ALL"){
                    $outputfile = "$OutputDirectory/OnboardedAccountTypes.html"
                    $titlesplit = "Onboarded Account Types"
                    $metricTag = "Account Metrics"
                    $recommendation1 = "Schedule regular account discovery scans to ensure that new privileged accounts are discovered and onboarded, and that existing accounts remain up-to-date. Monitor the account discovery process and review scan results for any anomalies or issues that may require attention."
                    $recommendation2 = "Expand the onboarding journey to identify different types of accounts that exist within the organization. Beyond traditional privileged accounts (such as windows or linux accounts), consider other types of accounts, such as service accounts, application accounts, and database accounts."
                    $recommendation3 = "Take the time to explore the various offerings available on the Idira (formerly CyberArk) Marketplace. Browse through the different categories, such as integrations, connectors, plugins, and extensions, to discover tools and solutions that will help to expand onboarding."
                    $OutputDataJSON = $OutputHash | ConvertTo-Json -Depth 100
                    $curTime = get-date -Format "MM/dd/yyyy HH:mm:ss"
                    if($HTMLChart -eq "ALL"){
                        $tablestr = "Bar Graph, Line Graph, Pie Chart"
                    }
                    else{
                        $tablestr = $HTMLChart
                    }
                    $metricexplanation = "This metric tracks the type of accounts that have been onboarded into the system. The account type is determined by the base type of the platform that the account is attached to"

                    $tempstr = ""
                    $tempstr2 = ""
                    $tempstr3 = ""
                    $tempstr4 = ""
                    $AllKeys = $OutputHash.Keys
                    $GetMinMax = @()

                    foreach($key in $AllKeys){
                        $curCount = $OutputHash.$key.counter
                        $GetMinMax += $curCount
                        $textColor =  '#{0:X6}' -f (Get-Random -Maximum 0x1000000)

                        $tempstr += "`"$key`","
                        $tempstr2 += "$curCount,"
                        $tempstr3 += "`"green`","
                        $tempstr4 += "`"$textColor`","
                    }

                    if($GetMinMax.count -ne 0){
                        $GetMinMax = $GetMinMax | Sort-Object
                        $mintick = 0
                        $maxtick = $GetMinMax[$GetMinMax.Count - 1]
                    }
                    else{
                        $mintick = 0
                        $maxtick = 0
                    }

                    if(![String]::IsNullOrEmpty($tempstr)){
                        $tempstr = $tempstr.Substring(0,$tempstr.Length-1)
                    }
                    if(![String]::IsNullOrEmpty($tempstr2)){
                        $tempstr2 = $tempstr2.Substring(0,$tempstr2.Length-1)
                    }
                    if(![String]::IsNullOrEmpty($tempstr3)){
                        $tempstr3 = $tempstr3.Substring(0,$tempstr3.Length-1)
                    }
                    if(![String]::IsNullOrEmpty($tempstr4)){
                        $tempstr4 = $tempstr4.Substring(0,$tempstr4.Length-1)
                    }

                    $htmlData += @{
                        Recommendation1 = $recommendation1
                        Recommendation2 = $recommendation2
                        Recommendation3 = $recommendation3
                        titlesplit = $titlesplit
                        outputfile = $outputfile
                        metricTag = $metricTag
                        OutputDataJSON = $OutputDataJSON
                        curTime = $curTime
                        tablestr = $tablestr
                        metricexplanation = $metricexplanation
                        HTMLChart = $HTMLChart
                        tempstr = $tempstr
                        tempstr2 = $tempstr2
                        tempstr3 = $tempstr3
                        tempstr4 = $tempstr4
                        datahash = $OutputHash
                        maxtick = $maxtick
                        mintick = $mintick
                    }
                }
            }
            if($TargetMetric -eq "AccountsOnboardedXDays"){
                $tagout = "accounts"
                if([String]::IsNullOrEmpty($DayRange)){
                    Write-VPASOutput -str "NO DayRange SUPPLIED, ENTER DayRange (1 - 365): " -type Y
                    $DayRange = Read-Host
                }
                if([String]::IsNullOrEmpty($AmtOfSets)){
                    Write-VPASOutput -str "NO AmtOfSets SUPPLIED, ENTER AmtOfSets (1 - 365): " -type Y
                    $AmtOfSets = Read-Host
                }

                try{
                    $AmtDaysInt = [Int]$DayRange
                    if($AmtDaysInt -lt 1 -or $AmtDaysInt -gt 365){
                        Write-Verbose "INVALID INPUT FOR DAY RANGE: $DayRange ...MUST BE AN INTEGRET BETWEEN 1 - 365"
                        Write-VPASOutput -str "INVALID INPUT FOR DAY RANGE: $DayRange ...MUST BE AN INTEGRET BETWEEN 1 - 365" -type E
                        return $false
                    }
                }catch{
                    Write-Verbose "INVALID INPUT FOR DAY RANGE: $DayRange ...MUST BE AN INTEGER BETWEEN 1 - 365"
                    Write-VPASOutput -str "INVALID INPUT FOR DAY RANGE: $DayRange ...MUST BE AN INTEGER BETWEEN 1 - 365" -type E
                    Write-VPASOutput -str $_ -type E
                    return $false
                }

                try{
                    $AmtSetsInt = [Int]$AmtOfSets
                    if($AmtSetsInt -lt 1 -or $AmtSetsInt -gt 365){
                        Write-Verbose "INVALID INPUT FOR SET AMOUNT: $AmtOfSets...MUST AN INTEGER BETWEEN 1 - 365"
                        Write-VPASOutput -str "INVALID INPUT FOR SET AMOUNT: $AmtOfSets...MUST AN INTEGER BETWEEN 1 - 365" -type E
                        return $false
                    }
                }catch{
                    Write-Verbose "INVALID INPUT FOR SET AMOUNT: $AmtOfSets ...MUST AN INTEGER BETWEEN 1 - 365"
                    Write-VPASOutput -str "INVALID INPUT FOR SET AMOUNT: $AmtOfSets ...MUST AN INTEGER BETWEEN 1 - 365" -type E
                    Write-VPASOutput -str $_ -type E
                    return $false
                }

                #INITIALIZE DATE HASH
                $AccountHash = @{}
                $CurTime = ([int][double]::Parse((Get-Date (get-date (get-date).Date).ToLocalTime() -UFormat %s))) + 86400
                $NumSeconds = ($AmtDaysInt * 86400)

                $counter = 0
                while($counter -lt $AmtSetsInt){
                    $counter += 1
                    $MaxNum = $CurTime - 1
                    $CurTime = $CurTime - $NumSeconds
                    $MinNum = $CurTime

                    $UniqueKey = "Set" + $counter
                    $AccountHash += @{
                        $UniqueKey = @{
                            Max = $MaxNum
                            Min = $MinNum
                            Count = 0
                            RawData = @()
                        }
                    }
                }

                $AllAccounts = Get-VPASAllAccounts -token $token
                if(!$AllAccounts){
                    Write-Verbose "FAILED TO PULL ALL ACCOUNTS"
                    Write-VPASOutput -str "FAILED TO PULL ALL ACCOUNTS" -type E
                    Write-VPASOutput -str $_ -type E
                    return $false
                }
                foreach($acct in $AllAccounts.value){
                    $validtargetplatform = $false
                    $validtargetsafe = $false
                    $validtargetusername = $false
                    $EpochStart = $acct.createdTime
                    $targetPlat = $acct.platformID
                    $targetSafe = $acct.safeName
                    $targetUsername = $acct.userName
                    $targetAccountName = $acct.name
                    $skipval = $false

                    if($PlatformSearchQuery.Count -eq 0){
                        $validtargetplatform = $true
                    }
                    else{
                        foreach($query in $PlatformSearchQuery){
                            if($targetPlat -match $query){
                                $validtargetplatform = $true
                            }
                        }
                    }

                    if($UsernameSearchQuery.Count -eq 0){
                        $validtargetusername = $true
                    }
                    else{
                        foreach($query in $UsernameSearchQuery){
                            if($targetUsername -match $query){
                                $validtargetusername = $true
                            }
                        }
                    }

                    if($SafeSearchQuery.Count -eq 0){
                        $validtargetsafe = $true
                    }
                    else{
                        foreach($query in $SafeSearchQuery){
                            if($targetSafe -match $query){
                                $validtargetsafe = $true
                            }
                        }
                    }

                    if(!$validtargetplatform -or !$validtargetsafe -or !$validtargetusername){
                        $skipval = $true
                    }

                    if(!$skipval){
                        foreach($ignoreval in $IgnoreSafes){
                            if($targetSafe -match $ignoreval){
                                Write-Verbose "SKIPPING $targetAccountName : SKIP VALUE $ignoreval FOUND IN SAFE $targetSafe"
                                $skipval = $true
                            }
                        }
                    }

                    if(!$skipval){
                        foreach($ignoreval in $IgnorePlatforms){
                            if($targetPlat -match $ignoreval){
                                Write-Verbose "SKIPPING $targetAccountName : SKIP VALUE $ignoreval FOUND IN PLATFORM $targetPlat"
                                $skipval = $true
                            }
                        }
                    }

                    if(!$skipval){
                        foreach($ignoreval in $IgnoreUsernames){
                            if($targetUsername -match $ignoreval){
                                Write-Verbose "SKIPPING $targetAccountName : SKIP VALUE $ignoreval FOUND IN USERNAME $targetUsername"
                                $skipval = $true
                            }
                        }
                    }

                    if(!$skipval){
                        $parser = $AmtSetsInt
                        while($parser -gt 0){
                            $uniqueKey = "Set$parser"
                            $setmin = $AccountHash.$uniqueKey.Min
                            $setmax = $AccountHash.$uniqueKey.Max
                            $setcount = $AccountHash.$uniqueKey.Count

                            if($EpochStart -ge $setmin -and $EpochStart -le $setmax){
                                $setcount += 1
                                $AccountHash.$uniqueKey.Count = $setcount
                                $parser = 0
                                $AccountHash.$UniqueKey.RawData += $acct
                            }
                            else{
                                $parser -= 1
                            }
                        }
                    }
                }

                #CONVERT THINGS TO HUMAN READABLE TIME
                $origin = New-Object -Type DateTime -ArgumentList 1970, 1, 1, 0, 0, 0, 0
                $parser = $AmtSetsInt
                while($parser -gt 0){
                    $uniqueKey = "Set$parser"
                    $setmin = $AccountHash.$uniqueKey.Min
                    $setmax = $AccountHash.$uniqueKey.Max

                    $newmin = $origin.AddSeconds($setmin).ToShortDateString()
                    $newmax = $origin.AddSeconds($setmax).ToShortDateString()

                    $AccountHash.$uniqueKey.Min = $newmin
                    $AccountHash.$uniqueKey.Max = $newmax

                    $parser -= 1
                }

                if($MetricFormat -eq "JSON" -or $MetricFormat -eq "ALL"){
                    $outputfile = "$OutputDirectory/AccountsOnboarded" + $DayRange + "Days.json"
                    $OutputDataJSON = $AccountHash | ConvertTo-Json -Depth 100
                    Write-Output $OutputDataJSON | Set-Content $outputfile
                }
                if($MetricFormat -eq "NONE"){
                    $htmlData += @{
                        datahash = $AccountHash
                    }
                }
                if($MetricFormat -eq "HTML" -or $MetricFormat -eq "ALL"){
                    $outputfile = "$OutputDirectory/AccountsOnboarded" + $DayRange + "Days.html"
                    $titlesplit = "Accounts Onboarded In The Last $DayRange Days"
                    $metricTag = "Account Metrics"
                    $recommendation1 = "Schedule regular account discovery scans to ensure that new privileged accounts are discovered and onboarded, and that existing accounts remain up-to-date. Monitor the account discovery process and review scan results for any anomalies or issues that may require attention."
                    $recommendation2 = "Expand the onboarding journey to identify different types of accounts that exist within the organization. Beyond traditional privileged accounts (such as windows or linux accounts), consider other types of accounts, such as service accounts, application accounts, and database accounts."
                    $recommendation3 = "Utilize Idira's (formerly CyberArk) Discovery and Audit (DNA) scanning, which is a feature used to discover and audit privileged accounts and secrets across your organization's IT infrastructure. Running frequent DNA scans helps ensure that your Idira (formerly CyberArk) Vault is up-to-date with the latest information about privileged accounts and secrets."
                    $OutputDataJSON = $AccountHash | ConvertTo-Json -Depth 100
                    $curTime = get-date -Format "MM/dd/yyyy HH:mm:ss"
                    if($HTMLChart -eq "ALL"){
                        $tablestr = "Bar Graph, Line Graph, Pie Chart"
                    }
                    else{
                        $tablestr = $HTMLChart
                    }
                    $metricexplanation = "This metric tracks how many accounts have been onboarded in the past $DayRange days, including configurable historical data"

                    $tempstr = ""
                    $tempstr2 = ""
                    $tempstr3 = ""
                    $tempstr4 = ""
                    $AllKeys = $AccountHash.Keys
                    $AmtKeys = $AllKeys.Count
                    $counter = $AmtKeys
